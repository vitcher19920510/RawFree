import { PrismaClient } from '@prisma/client';
import * as argon2 from 'argon2';

const prisma = new PrismaClient();

async function main() {
  console.log('🌱 Seed: начало инициализации...');

  // 1. Создаём супер-админа
  const passwordHash = await argon2.hash('Admin@12345'); // изменить в продакшене!
  
  await prisma.adminUser.upsert({
    where: { login: 'admin' },
    update: {},
    create: {
      login: 'admin',
      passwordHash,
      role: 'SUPERADMIN',
      isActive: true,
    },
  });

  console.log('✅ Супер-админ создан (login: admin, password: Admin@12345)');

  // 2. Создаём юридические документы
  await prisma.legalDoc.upsert({
    where: { code: 'terms' },
    update: {},
    create: {
      code: 'terms',
      title: 'Пользовательское соглашение',
      body: `Пользовательское соглашение RawFree\n\n1. Общие положения\nНастоящее Пользовательское соглашение (далее — Соглашение) регулирует отношения между владельцем сервиса RawFree (далее — Сервис) и пользователем Сервиса.\n\n2. Правила использования\n2.1. Запрещается создание множественных аккаунтов.\n2.2. Запрещается использование Сервиса для мошеннических действий.\n2.3. Запрещается распространение контента, нарушающий законодательство РФ.\n\n3. Подписка\n3.1. Доступ к основным функциям Сервиса осуществляется на платной основе.\n3.2. Стоимость подписки: 399 ₽ / 7 дней.\n3.3. Подписка автоматически продляется при отсутствии отмены.\n\n4. Конфиденциальность\n4.1. Сервис обязуется не передавать персональные данные пользователя третьим лицам, за исключением случаев, предусмотренных законодательством РФ.\n\n5. Ответственность\n5.1. Сервис не несёт ответственности за действия пользователей.\n5.2. Сервис не гарантирует доступность Сервиса 24/7.\n\n6. Контакты\nEmail: support@rawfree.ru`,
      version: '1.0',
    },
  });

  await prisma.legalDoc.upsert({
    where: { code: 'privacy' },
    update: {},
    create: {
      code: 'privacy',
      title: 'Политика конфиденциальности',
      body: `Политика конфиденциальности RawFree\n\n1. Сбор данных\nМы собираем следующие данные: email, телефон (опционально), имя, дату рождения, пол, город, геолокацию, фото профиля.\n\n2. Использование данных\nДанные используются для: предоставления услуг Сервиса, улучшения качества, персонализации ленты, отправки уведомлений.\n\n3. Хранение данных\nДанные хранятся на серверах в России. Мы используем шифрование и меры безопасности для защиты ваших данных.\n\n4. Права пользователя\nВы можете запросить удаление всех ваших данных в любое время через настройки аккаунта.\n\n5. Файлы cookie\nМы используем cookie для аутентификации и аналитики.\n\n6. Контакты\nEmail: privacy@rawfree.ru`,
      version: '1.0',
    },
  });

  console.log('✅ Юридические документы созданы');

  console.log('🌱 Seed: завершено!');
}

main()
  .catch((e) => {
    console.error('❌ Seed ошибка:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
